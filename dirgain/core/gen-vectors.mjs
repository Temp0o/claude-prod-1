import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createState, step, PARAM_KEYS } from "./dirgain.js";
import { PROFILES, allStreams } from "./streams.mjs";

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "vectors", "transform-vectors.txt");
const lines = ["# generated by core/gen-vectors.mjs from the JS reference transform"];
const streams = allStreams();
for (const [pname, p] of Object.entries(PROFILES)) {
  for (const [sname, events] of Object.entries(streams)) {
    lines.push(`# ${pname}/${sname}`);
    lines.push(["P", ...PARAM_KEYS.map((k) => p[k])].join(" "));
    const st = createState();
    for (const [dx, dy, dt] of events) {
      const [ox, oy] = step(p, st, dx, dy, dt);
      lines.push(`E ${dx} ${dy} ${dt} ${ox} ${oy}`);
    }
    lines.push("X");
  }
}
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n") + "\n");
console.log(`wrote ${out}`);
